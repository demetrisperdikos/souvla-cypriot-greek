const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
const BASE = process.env.BASE;
const data = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'data.json'), 'utf8'));
(async () => {
  const b = await chromium.launch({ executablePath: process.env.CHROME || undefined, args: ['--no-sandbox'] });
  const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
  const p = await ctx.newPage();
  const errs = []; p.on('pageerror', e => errs.push(e.message));
  await p.goto(BASE);
  await p.waitForSelector('.xp-val');
  await p.getByRole('button', { name: /Start diagnosis/ }).click();
  await p.waitForSelector('#view .question');
  const shown = (await p.locator('#view .question').first().innerText()).trim();
  const q = data.questions.find(x => x.text.trim() === shown);
  if (!q) throw new Error('shown question not found in data.json: ' + shown);
  const idx = q.options.findIndex(o => o.correct);
  await p.waitForSelector('.options button');
  await p.locator('.options button').nth(idx).click();
  await p.waitForTimeout(300);
  const xpBefore = Number(await p.locator('.xp-val').innerText());
  const streakBefore = Number(await p.locator('.stat-val').first().innerText());
  await p.reload();
  await p.waitForSelector('.xp-val');
  const xpAfter = Number(await p.locator('.xp-val').innerText());
  const streakAfter = Number(await p.locator('.stat-val').first().innerText());
  const ok = xpBefore > 0 && xpAfter === xpBefore && streakAfter === streakBefore && streakAfter >= 1 && errs.length === 0;
  console.log(`${ok ? 'PASS' : 'FAIL'} reload: xp ${xpBefore}->${xpAfter}, streak ${streakBefore}->${streakAfter}, errors ${errs.length}`);
  await b.close();
  if (!ok) process.exit(1);
})().catch(e => { console.log('FAIL reload: ' + e.message); process.exit(1); });
