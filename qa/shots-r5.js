const { chromium } = require('playwright');
const BASE = process.env.BASE;
const CHROME = process.env.CHROME || undefined;
(async () => {
  const b = await chromium.launch({ executablePath: CHROME, args: ['--no-sandbox'] });
  const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
  await p.goto(BASE);
  await p.locator('#lessons').scrollIntoViewIfNeeded();
  await p.waitForTimeout(300);
  await p.screenshot({ path: '../.shots/r5-desktop-lessons.png' });
  await p.goto(BASE);
  await p.getByRole('button', { name: 'Start diagnosis' }).click();
  await p.waitForTimeout(300);
  await p.screenshot({ path: '../.shots/r5-quiz-1440.png' });
  await p.goto(BASE);
  await p.getByRole('button', { name: 'Open First Greetings' }).click();
  await p.waitForTimeout(300);
  await p.screenshot({ path: '../.shots/r5-flashcard-1440.png' });
  await b.close();
  console.log('shots ok');
})().catch(e => { console.error(e.message); process.exit(1); });
